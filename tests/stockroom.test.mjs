import test from 'node:test'
import assert from 'node:assert/strict'
import {harness} from './purse-harness.mjs'

test('STOCK-001 counts create one preferred-item draft; a person submits and outstanding supply prevents duplicates', async t => {
  const h = await harness()
  t.after(() => h.close())
  const {command, state, send} = h
  await command('business', {name:'Site supplies',currencies:['USD'],locations:['Austin'],costCentres:['Operations'],projects:['Site upkeep']})
  const buyer = await h.member('stock-buyer@example.test',['buyer'])
  const requester = await h.member('employee@example.test',['requester'])
  const approver = await h.member('stock-approver@example.test',['approver'])
  const supplier = await command('supplier',{name:'Preferred supplies',status:'preferred',reason:'Approved consumables supplier',contacts:[]},buyer)
  const catalogue = await command('catalogue',{description:'Cleaning concentrate',supplier:supplier.id,currency:'USD',unitMinor:1250,category:'Cleaning',approved:true},buyer)
  const input = {name:'Site cleaning concentrate',catalogue:catalogue.id,location:'Austin',costCentre:'Operations',project:'Site upkeep',reorderPoint:'5',replenishTo:'10',needDate:'2026-12-01',terms:'Supplier quote CS-1; net 30'}
  await command('stockroom-item',input,requester,403)
  assert.equal((await send('/api/purse/command/stockroom-item',input)).status,401)
  const stock = await command('stockroom-item',input,buyer)
  assert.equal((await state()).data.request.length,0)
  await command('stockroom-item',input,buyer,409)
  let count = await command('stockroom-count',{id:stock.id,count:'5'},buyer)
  assert.equal(count.request,null)
  await command('catalogue',{...catalogue,unitMinor:1400},buyer)
  count = await command('stockroom-count',{id:stock.id,count:'2.500'},buyer)
  assert.ok(count.requestCreated)
  const draft = (await state()).data.request.find(r => r.id === count.request)
  assert.equal(draft.status,'draft')
  assert.equal(draft.supplier,supplier.id)
  assert.equal(draft.lines[0].catalogue,catalogue.id)
  assert.equal(draft.lines[0].quantity,'7.5')
  assert.equal(draft.lines[0].unitMinor,1400)
  assert.equal(draft.lines[0].project,'Site upkeep')
  assert.equal(draft.location,'Austin')
  assert.equal(draft.costCentre,'Operations')
  assert.equal(draft.needDate,input.needDate)
  assert.equal(draft.totalMinor,10500)
  assert.equal((await state()).data.commitment.length,0)
  const repeated = await command('stockroom-count',{id:stock.id,count:'1'},buyer)
  assert.equal(repeated.request,draft.id)
  assert.equal(repeated.requestCreated,false)
  assert.equal((await state()).data.request.length,1)
  await command('submit',{id:draft.id,revision:draft.revision},buyer,403)
  await command('policy',{name:'Cleaning approval',currency:'USD',category:'Cleaning',project:'Site upkeep',approver:'stock-approver@example.test',limitMinor:100000,budgetMinor:100000})
  const submitted = await command('submit',{id:draft.id,revision:draft.revision})
  assert.equal(submitted.status,'pending')
  await command('stockroom-count',{id:stock.id,count:'0'},buyer)
  assert.equal((await state()).data.request.length,1)
  await command('decision',{id:draft.id,revision:draft.revision,decision:'approved',reason:'Consumables reviewed'},approver)
  const order = await command('convert',{id:draft.id,revision:draft.revision},buyer)
  await command('issue',{id:order.id,revision:order.revision,reason:'Issued after approval'},buyer)
  await command('receipt',{order:order.id,line:order.lines[0].id,event:'receive',quantity:'1',reason:'Partial delivery'})
  await command('stockroom-count',{id:stock.id,count:'1'},buyer)
  assert.equal((await state()).data.request.length,1)
  await command('receipt',{order:order.id,line:order.lines[0].id,event:'receive',quantity:'6.5',reason:'Delivery complete'})
  await command('catalogue',{...catalogue,unitMinor:1500},buyer)
  const next = await command('stockroom-count',{id:stock.id,count:'0.125'},buyer)
  assert.ok(next.requestCreated)
  assert.notEqual(next.request,draft.id)
  let data = (await state()).data
  const replenishment = data.request.find(r => r.id === next.request)
  assert.equal(replenishment.status,'draft')
  assert.equal(replenishment.lines[0].quantity,'9.875')
  assert.equal(replenishment.lines[0].unitMinor,1500)
  assert.equal(data.revision.find(r => r.request === draft.id).lines[0].unitMinor,1400)
  assert.equal(data.stockroom.find(s => s.id === stock.id).count,'0.125')
  for (const invalid of ['-1','NaN','Infinity','1.0001',1,null]) {
    const before = (await state()).data
    await command('stockroom-count',{id:stock.id,count:invalid},buyer,400)
    assert.deepEqual((await state()).data,before)
  }
  const before = (await state()).data
  await command('stockroom-count',{id:stock.id,count:'2'},requester,403)
  await command('stockroom-item',{...input,id:stock.id,replenishTo:'4'},buyer,400)
  assert.deepEqual((await state()).data,before)
  const pier = await command('request',{title:'Pier replenishment: cleaning concentrate',supplier:supplier.id,currency:'USD',needDate:'2026-12-01',location:'Austin',costCentre:'Operations',terms:'Net 30',lines:[{catalogue:catalogue.id,quantity:'4',project:'Site upkeep'}]},requester)
  assert.equal(pier.status,'draft')
  assert.equal(pier.requesterEmail,'employee@example.test')
  await command('supplier',{...supplier,status:'blocked',reason:'Supplier review'},buyer)
  await command('stockroom-item',{...input,name:'Blocked stock',location:'Austin'},buyer,409)
  data = (await state()).data
  assert.equal(data.request.length,3)
  assert.ok(data.audit.some(a => a.action === 'stockroom-count' && a.record === stock.id && a.request === draft.id))
})
