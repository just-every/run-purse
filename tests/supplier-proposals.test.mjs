test('Pending supplier review preserves approval, returns unissued requests and releases exact reservations once through native HTTP',async t=>{
    const f=await supplierProposalsFixture();t.after(()=>f.h.close());const {h}=f;
    const p=await f.propose(),request=await h.command('request',f.requestInput(p.id),f.requester);
    await f.approve(request);
    let state=(await h.state()).data;
    const history=structuredClone(state.decision),revision=structuredClone(state.revision);
    assert.equal(state.commitment.filter(e=>e.request===request.id).reduce((n,e)=>n+e.amountMinor,0),90000);
    assert.equal(state.totals.USD,90000);
    assert.equal((await h.state(f.requester)).data.request.find(r=>r.id===request.id).supplierReview.status,'pending');
    const convert=await h.send('/api/purse/command/convert',{id:request.id,revision:1},f.buyer);
    assert.equal(convert.status,409);assert.match(convert.value.error,/Supplier pending vendor approval/);
    assert.equal(state.order.length,0);
    const combined=await h.send('/api/purse/command/convert',{id:request.id,revision:1,issue:true},f.buyer);assert.equal(combined.status,409);assert.match(combined.value.error,/Supplier pending vendor approval/);
    const captured=await f.review(p.id),before=await f.snapshot();
    for(const cookie of [f.requester,f.buyer,f.approver])await h.command('supplier-proposal-reject',captured,cookie,403);
    assert.equal((await h.send('/api/purse/command/supplier-proposal-reject',captured)).status,401);
    for(const op of ['supplier','screen-supplier','review-screening'])await h.command(op,{id:p.id,name:p.name,status:'active',reason:'Attempt direct activation',decision:'clear'},h.owner,409);
    await h.command('supplier-proposal-reject',{...captured,reason:''},h.owner,400);
    assert.deepEqual(await f.snapshot(),before,'Refused reviews and activation attempts change nothing');
    // An affected request changing after review invalidates the entire rejection.
    const second=await h.command('request',{...f.requestInput(p.id),title:'synthetic-purse-6813 second request'},f.requester);
    await h.command('supplier-proposal-reject',captured,h.owner,409);
    const fresh=await f.review(p.id),responses=await Promise.all([h.send('/api/purse/command/supplier-proposal-reject',fresh,h.owner),h.send('/api/purse/command/supplier-proposal-reject',fresh,h.owner)]);
    assert.deepEqual(responses.map(r=>r.status).sort(),[200,409]);
    state=(await h.state()).data;
    assert.equal(state.totals.USD,0);
    assert.equal(state.commitment.filter(e=>e.kind==='supplier-rejection-release').length,1);
    const release=state.commitment.find(e=>e.kind==='supplier-rejection-release');
    assert.equal(release.amountMinor,-90000);assert.deepEqual(release.budgetAllocations,[{policy:f.policy.id,amountMinor:-90000}]);
    assert.equal(state.request.find(r=>r.id===request.id).status,'returned');
    assert.equal(state.request.find(r=>r.id===second.id).status,'returned');
    assert.equal(state.request.find(r=>r.id===request.id).supplierRejection.reason,fresh.reason);
    assert.deepEqual(state.decision,history);assert.deepEqual(state.revision.filter(r=>r.request===request.id),revision.filter(r=>r.request===request.id));
    const after=await f.snapshot();await h.command('supplier-proposal-reject',fresh,h.owner,409);assert.deepEqual(await f.snapshot(),after);
    await h.command('submit',{id:request.id,revision:1},f.requester,409);
    await h.command('supplier',{id:p.id,name:p.name,status:'active',reason:'Rejected proposal bypass'},f.buyer,409);
    const replacement=await h.command('amend',{...f.requestInput(f.active.id),id:request.id,revision:1,reason:'Choose the reviewed existing caterer'},f.requester);
    assert.equal(replacement.revision,2);assert.equal(replacement.status,'draft');assert.equal((await h.state()).data.totals.USD,0);
    await h.command('convert',{id:replacement.id,revision:2},f.buyer,409);
    await f.approve(replacement);
    const order=await h.command('convert',{id:replacement.id,revision:2},f.buyer);
    await h.command('issue',{id:order.id,revision:2,reason:'Issue newly approved existing supplier purchase'},f.buyer);
    state=(await h.state()).data;
    assert.equal(state.totals.USD,90000);assert.equal(state.decision.filter(d=>d.request===request.id&&d.decision==='approved').length,2);
    assert.equal(state.decision.find(d=>d.request===request.id&&d.revision===1).id,history.find(d=>d.request===request.id).id);
    assert.equal(validatePurchasingArchive(await f.snapshot()),true);
    const audits=(await h.send('/api/purse/audit',undefined,h.owner)).value.events;
    assert.equal(audits.filter(e=>e.action==='supplier-proposal-reject').length,1);
    assert.equal(audits.filter(e=>e.action==='supplier-rejection-return').length,2);
    assert.ok((await h.send('/api/purse/audit.csv',undefined,h.owner)).value.includes(fresh.reason));
});

test('Supplier proposal choices preserve duplicate privacy, proposer separation and current native authority',async t=>{
    const f=await supplierProposalsFixture();t.after(()=>f.h.close());const {h}=f;
    const p=await f.propose(),before=await f.snapshot();
    const other=(await h.state(f.other)).data;
    assert.ok(!other.supplier.some(s=>s.id===p.id));assert.equal(other.supplierProposal.length,0);
    const supplierAdmin=(await h.state(f.buyer)).data;
    assert.ok(supplierAdmin.supplier.some(s=>s.id===p.id),'Unrestricted buyers retain the minimal pending register entry');
    assert.equal(supplierAdmin.supplierProposal.length,0,'Supplier register access does not expose private proposal contacts');
    assert.ok(!JSON.stringify(supplierAdmin.supplier.find(s=>s.id===p.id)).includes(p.contactEmail));
    const hidden=await h.command('supplier-proposal-choices',f.input(6811),f.other);
    assert.equal(hidden.matches.length,0);assert.equal(hidden.needsAdministrator,true);
    assert.ok(!JSON.stringify(hidden).includes(p.id));assert.ok(!JSON.stringify(hidden).includes(p.contactEmail));
    await h.command('supplier-propose',f.input(6811),f.other,409);
    assert.deepEqual(await f.snapshot(),before);
    const choices=await h.command('supplier-proposal-choices',{name:'synthetic-purse-6819 new spelling',contactEmail:proposalEmail(6807)},f.requester);
    assert.equal(choices.matches[0].id,f.active.id);assert.equal(choices.matches[0].selectable,true);
    const byWebsite=await h.command('supplier-proposal-choices',{name:'synthetic-purse-6820',contactEmail:proposalEmail(6821),website:'https://supplier-6807.example.test/offers'},f.requester);
    assert.equal(byWebsite.matches[0].id,f.active.id);
    assert.ok(!JSON.stringify(choices).includes(proposalEmail(6807)),'Choices expose no contact or protected matching evidence');
    const blocked=await h.command('supplier',{...f.active,status:'blocked',reason:'Compliance restriction'});
    const denied=await h.command('supplier-proposal-choices',{name:blocked.name,contactEmail:proposalEmail(6807)},f.requester);
    assert.equal(denied.matches[0].status,'blocked');assert.equal(denied.matches[0].selectable,false);
    await h.command('supplier-propose',{...f.input(6824),name:blocked.name},f.requester,409);
    await h.command('request',f.requestInput(blocked.id),f.requester,409);
    await h.command('supplier-propose',{...f.input(6826),tin:'synthetic-purse-6827'},f.requester,400);
    const self=await f.propose(6828,h.owner);
    await h.command('supplier-proposal-reject',await f.review(self.id),h.owner,403);
    const buyerProposal=await f.propose(6830,f.buyer);
    await h.command('supplier-proposal-reject',await f.review(buyerProposal.id),f.buyer,403);
    // A purchasing role named owner does not replace a native owner session.
    await h.command('member',{email:proposalEmail(6832),name:'synthetic-purse-6832',roles:['owner'],active:true},h.owner,400);
    const captured=await f.review(p.id),state=await f.snapshot(),owner=(await h.state()).actor.id;
    await h.db.prepare('UPDATE oa_sessions SET revoked_at=? WHERE operator_id=?').bind(Date.now(),owner).run();
    assert.equal((await h.send('/api/purse/command/supplier-proposal-reject',captured,h.owner)).status,401);
    assert.deepEqual(await f.snapshot(),state,'A revoked native credential cannot replay a supplier review');
});

test('Supplier proposal erasure and archive continuation retain inert review and release history without resurrecting identity',async t=>{
    const f=await supplierProposalsFixture();t.after(()=>f.h.close());const {h}=f;
    const p=await f.propose(),request=await h.command('request',f.requestInput(p.id),f.requester);await f.approve(request);
    const review=await f.review(p.id);await h.command('supplier-proposal-reject',review);
    const archive=async name=>{const file=join(h.dir,name+'.rer');await exportArchive(await createPortability({db:h.db,buckets:{ORIGINALS:h.originals},policy:portability}),file,[]);return file;};
    const saved=await archive('synthetic-purse-6840'),copy=await harness({empty:true});t.after(()=>copy.close());
    await importArchive(await createPortability({db:copy.db,buckets:{ORIGINALS:copy.originals},policy:portability}),saved,[]);
    const boot=await copy.send('/auth/bootstrap',{token:'synthetic-local-test-bootstrap-token-0123456789',displayName:'synthetic-purse-6841'});assert.equal(boot.status,303);
    copy.owner=boot.cookie;
    const restored=(await copy.send('/api/purse/state',undefined,boot.cookie)).value.data;
    assert.equal(restored.supplierProposal[0].status,'rejected');assert.equal(restored.supplierProposal[0].mayReject,false);assert.equal(restored.totals.USD,0);
    assert.equal(restored.decision.find(d=>d.request===request.id).decision,'approved');
    assert.equal((await copy.send('/api/purse/command/supplier-proposal-reject',review,boot.cookie)).status,409);
    assert.equal((await copy.send('/api/purse/command/supplier',{id:p.id,name:p.name,status:'active',reason:'Restored history cannot activate'},boot.cookie)).status,409);
    assert.equal((await copy.send('/api/purse/command/convert',{id:request.id,revision:1},boot.cookie)).status,409);
    assert.equal((await copy.send('/api/purse/command/supplier-proposal-reject',review,h.owner)).status,401);
    await reauthenticateErasure(h);
    const inventory=(await h.send('/api/purse/erasure',undefined,h.owner)).value;
    const preview=await h.send('/api/purse/erasure/preview',{kind:'contact',id:p.id,email:p.contactEmail,revision:inventory.revision},h.owner);assert.equal(preview.status,200,JSON.stringify(preview.value));
    const erased=await h.send('/api/purse/erasure/execute',{...preview.value.subject,revision:preview.value.revision,review:preview.value.review,fingerprint:preview.value.fingerprint,consent:true},h.owner);assert.equal(erased.status,200,JSON.stringify(erased.value));
    const anonymous=(await h.state()).data.supplierProposal.find(v=>v.id===p.id);assert.ok(anonymous.erasure);assert.ok(!JSON.stringify(anonymous).includes(p.contactEmail));assert.equal(anonymous.mayReject,false);
    // Departed requester credentials and captured proposal inputs cannot recreate erased personal data.
    await h.command('member',{email:proposalEmail(6801),name:'synthetic-purse-6801',roles:['requester'],active:false});
    const memberInventory=(await h.send('/api/purse/erasure',undefined,h.owner)).value;
    const memberReview=await h.send('/api/purse/erasure/preview',{kind:'member',id:proposalEmail(6801),revision:memberInventory.revision},h.owner);assert.equal(memberReview.status,200,JSON.stringify(memberReview.value));
    const memberErased=await h.send('/api/purse/erasure/execute',{...memberReview.value.subject,revision:memberReview.value.revision,review:memberReview.value.review,fingerprint:memberReview.value.fingerprint,consent:true},h.owner);assert.equal(memberErased.status,200,JSON.stringify(memberErased.value));
    const erasedState=await f.snapshot();
    assert.equal((await h.send('/api/purse/command/supplier-propose',f.input(6811),f.requester)).status,401);
    assert.deepEqual(await f.snapshot(),erasedState);
    assert.equal(validatePurchasingArchive(await f.snapshot()),true);
    const latest=await archive('synthetic-purse-6842'),destination=await harness({empty:true});t.after(()=>destination.close());
    await assert.rejects(importArchive(await createPortability({db:destination.db,buckets:{ORIGINALS:destination.originals},policy:portability}),saved,[],latest),/erasure|journal/i);
    const finalCopy=await harness({empty:true});t.after(()=>finalCopy.close());
    await importArchive(await createPortability({db:finalCopy.db,buckets:{ORIGINALS:finalCopy.originals},policy:portability}),latest,[]);
    const finalBoot=await finalCopy.send('/auth/bootstrap',{token:'synthetic-local-test-bootstrap-token-0123456789',displayName:'synthetic-purse-6843'});assert.equal(finalBoot.status,303);
    const finalState=(await finalCopy.send('/api/purse/state',undefined,finalBoot.cookie)).value.data;
    assert.equal(finalState.totals.USD,0);assert.ok(finalState.supplierProposal[0].erasure);assert.ok(!JSON.stringify(finalState.supplierProposal).includes(p.contactEmail));
    assert.equal((await finalCopy.send('/api/purse/command/supplier-proposal-reject',review,finalBoot.cookie)).status,409);
});
